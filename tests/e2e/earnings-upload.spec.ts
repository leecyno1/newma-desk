import {expect,test} from '@playwright/test';
import {existsSync} from 'node:fs';
import path from 'node:path';

const pdf=process.env.REAL_EARNINGS_PDF||path.resolve('output/pdf/kweichow-moutai-2024-annual-report.pdf');
test('existing real PDF enriches its workbook without uploading again or overwriting edits',async({page,request},testInfo)=>{
  test.skip(!existsSync(pdf),'Real-file acceptance requires the public Moutai annual report');
  const workspace=`real-earnings-enrich-${Date.now()}`,user='real-earnings-enrich';
  await page.addInitScript(({workspace,user})=>{localStorage.setItem('vibedesk.userId.v1',user);localStorage.setItem('vibedesk.workspaceId.v1',workspace)},{workspace,user});
  await page.route('https://fonts.googleapis.com/**',route=>route.abort());
  let uploads=0;
  page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/myreports'))uploads++});
  const ready=page.waitForResponse(r=>r.request().method()==='GET'&&r.url().includes('/storage/earnings-workbench/workbooks'));
  await page.goto(`http://127.0.0.1:5888/?mod=earnings-workbench&workspace=${workspace}`);await ready;
  const frame=page.frameLocator('iframe[title="财报研究"]');
  const read=async()=>(await(await request.get('http://127.0.0.1:8911/api/mods/earnings-workbench/context',{headers:{'X-User-Id':user,'X-Workspace-Id':workspace}})).json()).context;
  await frame.getByLabel('选择财报 PDF',{exact:true}).setInputFiles(pdf);
  const choices=frame.getByRole('region',{name:'经营讨论候选'});
  await expect(choices.getByRole('checkbox')).toHaveCount(7);
  for(const checkbox of await choices.getByRole('checkbox').all())await checkbox.uncheck();
  await frame.getByLabel('已核对财报身份、期间、单位和选中指标',{exact:true}).check();
  await frame.getByRole('button',{name:'确认新建并保存底稿'}).click();
  await expect(frame.getByText('真实财报已保存到 Desk 工作区；选中指标和经营讨论已入库，其他指标保持缺失。',{exact:true})).toBeVisible();
  await page.reload();
  const supplement=frame.getByRole('region',{name:'补充已有财报原文'});
  await expect(supplement).toBeVisible();
  await expect.poll(async()=>(await read())?.data?.summary?.sourceMaterials?.length).toBe(7);
  const original=await read();
  // A failed reread must leave the old workbook intact and allow retry.
  await page.route('**/myreports/*/earnings-candidates',route=>route.fulfill({status:503,json:{detail:'验收：文件暂时不可读'}}),{times:1});
  await supplement.getByRole('button',{name:'补充已上传财报原文',exact:true}).click();
  await expect(supplement.getByRole('alert')).toBeVisible();
  expect((await read()).data.summary.sourceMaterials).toEqual(original.data.summary.sourceMaterials);
  await supplement.getByRole('button',{name:'补充已上传财报原文',exact:true}).click();
  await expect(supplement.getByRole('region',{name:'经营讨论候选'})).toBeVisible();
  await expect(supplement.getByRole('button',{name:'确认补充到草稿'})).toBeDisabled();
  expect((await read()).data.summary.sourceMaterials).toEqual(original.data.summary.sourceMaterials);
  await supplement.getByRole('button',{name:'取消补充',exact:true}).click();
  await expect(supplement.getByRole('region',{name:'经营讨论候选'})).toHaveCount(0);
  await supplement.getByRole('button',{name:'补充已上传财报原文',exact:true}).click();
  await expect(supplement.getByRole('region',{name:'经营讨论候选'})).toBeVisible();
  // Edits made while previewing must survive the addition.
  await frame.getByLabel('营业收入 内部预期',{exact:true}).fill('1800');
  await frame.getByRole('textbox',{name:'一句话结论',exact:true}).fill('保留我的研究结论');
  await supplement.getByLabel('已核对补充的经营讨论原文',{exact:true}).check();
  await supplement.getByRole('button',{name:'确认补充到草稿',exact:true}).click();
  await expect(supplement).toContainText('已补充到当前草稿');
  await expect(frame.getByLabel('营业收入 内部预期',{exact:true})).toHaveValue('1800');
  await frame.getByRole('button',{name:'保存',exact:true}).click();
  await expect(frame.getByText('已保存到 Desk 工作区',{exact:true})).toBeVisible();
  await page.reload();
  await expect(frame.getByRole('textbox',{name:'一句话结论',exact:true})).toHaveValue('保留我的研究结论');
  await expect(frame.getByLabel('营业收入 内部预期',{exact:true})).toHaveValue('1800');
  await expect.poll(async()=>(await read())?.data?.summary?.sourceMaterials?.filter((s:any)=>s.discussion).length).toBe(7);
  const saved=await read();
  expect(saved.selection.workbookId).toBe(original.selection.workbookId);
  expect(saved.data.summary.sourceMaterials.slice(0,7)).toEqual(original.data.summary.sourceMaterials);
  expect(saved.data.summary.metrics.map((m:any)=>m.reported)).toEqual(original.data.summary.metrics.map((m:any)=>m.reported));
  await supplement.getByRole('button',{name:'补充已上传财报原文',exact:true}).click();
  await expect(supplement).toContainText('已全部采用，不重复添加');
  expect(uploads).toBe(1);
  await supplement.screenshot({path:testInfo.outputPath('existing-pdf-enriched.png'),animations:'disabled'});
});

test('real annual PDF uploads, populates a saved workbook and reaches the unified Agent',async({page,request},testInfo)=>{
  test.skip(!existsSync(pdf),'Download the public Moutai 2024 annual report to run real-file acceptance');
  test.setTimeout(process.env.RUN_LIVE_EARNINGS_AGENT==='1'?300_000:90_000);
  const workspace=`real-earnings-upload-${Date.now()}`,user='real-earnings-upload';
  await page.addInitScript(({workspace,user})=>{localStorage.setItem('vibedesk.userId.v1',user);localStorage.setItem('vibedesk.workspaceId.v1',workspace)},{workspace,user});
  await page.route('https://fonts.googleapis.com/**',route=>route.abort());
  const ready=page.waitForResponse(r=>r.request().method()==='GET'&&r.url().includes('/storage/earnings-workbench/workbooks'));
  await page.goto(`http://127.0.0.1:5888/?mod=earnings-workbench&workspace=${workspace}`);await ready;
  const frame=page.frameLocator('iframe[title="财报研究"]');
  const uploaded=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/myreports'));
  await frame.getByLabel('选择财报 PDF',{exact:true}).setInputFiles(pdf);
  const report=(await (await uploaded).json()).data;
  await expect(frame.getByRole('table',{name:'PDF 指标候选'})).toContainText('1,708.9915');
  await expect(frame.getByRole('table',{name:'PDF 指标候选'}).getByRole('row')).toHaveCount(8);
  const discussions=frame.getByRole('region',{name:'经营讨论候选'});
  await expect(discussions).toContainText('第 13 页');
  await discussions.locator('summary').filter({hasText:'第 13 页'}).click();
  await expect(discussions).toContainText('经销商预付货款减少');
  // Excluded evidence must not reach the saved workbook or Agent.
  await discussions.getByLabel('采用经营讨论第 14 页',{exact:true}).uncheck();
  await expect(frame.getByRole('button',{name:'确认新建并保存底稿'})).toBeDisabled();
  await frame.getByLabel('已核对财报身份、期间、单位和选中指标',{exact:true}).check();
  await frame.getByRole('button',{name:'确认新建并保存底稿'}).click();
  await expect(frame.getByText('真实财报已保存到 Desk 工作区；选中指标和经营讨论已入库，其他指标保持缺失。',{exact:true})).toBeVisible();
  await page.reload();
  await expect(frame.getByLabel('营业收入 实际',{exact:true})).toHaveValue('1708.9915227634');
  await expect(frame.getByLabel('归母净利润 实际',{exact:true})).toHaveValue('862.2814642162');
  await expect(frame.getByLabel('毛利率 实际',{exact:true})).toHaveValue('');
  await expect(frame.getByLabel('财报当前数据状态')).toContainText('6/9');
  await expect(frame.getByLabel('财报关键实际值')).toContainText('1,708.99');
  await expect(frame.getByLabel('财报关键实际值')).toContainText('924.64');
  const context=async()=>(await(await request.get(`http://127.0.0.1:8911/api/mods/earnings-workbench/context`,{headers:{'X-User-Id':user,'X-Workspace-Id':workspace}})).json()).context;
  await expect.poll(async()=>(await context())?.data?.summary?.sourceMaterials?.[0]?.importedReport?.reportId).toBe(report.id);
  expect((await context()).data.summary.operatingMetrics[0].reported).toBeCloseTo(924.6369216843,8);
  const savedDiscussion=(await context()).data.summary.sourceMaterials.filter((source:any)=>source.discussion);
  expect(savedDiscussion.map((source:any)=>source.discussion.pdfPage)).toEqual([9,12,13,16,21,22]);
  expect(savedDiscussion.find((source:any)=>source.discussion.pdfPage===13).discussion.text).toContain('经销商预付货款减少');
  const savedEvidence=frame.getByRole('region',{name:'已采用经营讨论'});
  await savedEvidence.locator('summary').filter({hasText:'第 16 页'}).click();
  await expect(savedEvidence).toContainText('-10.51');
  await savedEvidence.screenshot({path:testInfo.outputPath('real-pdf-adopted.png'),animations:'disabled'});
  await frame.getByRole('button',{name:'分析此底稿',exact:true}).click();
  const question=page.locator('.mod-copilot-composer textarea');
  await expect(question).toHaveValue(/请分析当前财报底稿/);
  if(process.env.RUN_LIVE_EARNINGS_AGENT==='1'){
    const taskResponse=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/api/agent/tasks'));
    await page.getByRole('button',{name:'发送',exact:true}).click();
    const task=await(await taskResponse).json();
    let final:any;
    await expect.poll(async()=>{final=await(await request.get(`http://127.0.0.1:8911/api/agent/tasks/${task.id}`)).json();return final.status},{timeout:240_000,intervals:[1000,2000,5000]}).toBe('completed');
    expect(final.result.answer).toMatch(/1[,]?708|1708/);
    expect(final.result.answer).toContain('合同负债');
    expect(final.result.answer).toMatch(/归集|财务公司|成员单位/);
    const answer=page.locator('.copilot-message.assistant').last();
    await expect(answer.locator('.copilot-message-body')).not.toBeEmpty();
    const expand=answer.getByRole('button',{name:'展开完整回答',exact:true});
    if(final.result.answer.length>1600||final.result.answer.split('\n').length>18)await expand.click();
    await expect(answer).toContainText(/1[,]?708|1708/);
    await testInfo.attach('real-agent-answer',{body:final.result.answer,contentType:'text/plain'});
  }
  await page.screenshot({path:testInfo.outputPath('real-pdf-workbench.png'),animations:'disabled'});
});
