def normalize_industry_label(value: str) -> str:
    """Normalize whitespace and common ASCII level suffixes."""

    name = re.sub(r"\s+", "", str(value or "").strip())
    name = re.sub(r"III$", "Ⅲ", name, flags=re.IGNORECASE)
    return re.sub(r"II$", "Ⅱ", name, flags=re.IGNORECASE)


def normalize_industry_name(value: str) -> str:
    """Normalize common Desk suffixes without guessing the industry."""

    return re.sub(r"(?:Ⅱ|Ⅲ)$", "", normalize_industry_label(value))


def industry_aliases(industry: str) -> Tuple[str, ...]:
    return SW_2021_L1_ALIASES.get(industry, (industry,))


_ALIAS_TO_INDUSTRY = {
    normalize_industry_name(alias): industry
    for industry, aliases in SW_2021_L1_ALIASES.items()
    for alias in aliases
}

_L2_LABEL_TO_OFFICIAL = {
    normalize_industry_label(name): name for name in SW_2021_L2_TO_L1
}
_L2_BASE_TO_OFFICIAL: Dict[str, Tuple[str, ...]] = {}
for _l2_name in SW_2021_L2_TO_L1:
    _base_name = normalize_industry_name(_l2_name)
    _L2_BASE_TO_OFFICIAL[_base_name] = (
        *_L2_BASE_TO_OFFICIAL.get(_base_name, ()),
        _l2_name,
    )


def _official_sw_l2_label(value: str) -> str:
    label = normalize_industry_label(value)
    if not label:
        return ""
    exact = _L2_LABEL_TO_OFFICIAL.get(label)
    if exact:
        return exact
    candidates = _L2_BASE_TO_OFFICIAL.get(normalize_industry_name(label), ())
    return candidates[0] if len(candidates) == 1 else ""


def resolve_sw_l1_industry(value: str) -> str:
    """Resolve a known Desk/申万 industry name to SW 2021 level-1."""

    official_l2 = _official_sw_l2_label(value)
    if official_l2:
        return SW_2021_L2_TO_L1[official_l2]
    name = normalize_industry_name(value)
    if not name:
        return UNCLASSIFIED_INDUSTRY
    exact = _ALIAS_TO_INDUSTRY.get(name)
    if exact:
        return exact
    for alias in sorted(_ALIAS_TO_INDUSTRY, key=len, reverse=True):
        if len(alias) >= 4 and alias in name:
            return _ALIAS_TO_INDUSTRY[alias]
    return UNCLASSIFIED_INDUSTRY


def resolve_sw_l2_industry(value: str, l1_industry: str | None = None) -> str:
    """Return a verified SW 2021 level-2 label, or an empty string.

    A broad Desk label such as ``银行Ⅱ`` is not promoted to level-2 because
    SW 2021 splits banks into state-owned, joint-stock, city and rural banks.
    """

    official = _official_sw_l2_label(value)
    if not official:
        return ""
    parent = SW_2021_L2_TO_L1[official]
    if l1_industry and l1_industry != UNCLASSIFIED_INDUSTRY and parent != l1_industry:
        return ""
    return official
